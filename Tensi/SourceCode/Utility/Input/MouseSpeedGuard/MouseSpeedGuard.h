#pragma once

/************************************************
*	マウス速度の復元保証.
*	  クラッシュや強制終了などでアプリが正常終了しなかった場合でも、
*	  マウス速度が必ず元に戻るように多層で保証する.
*	   1. クラッシュハンドラ : 未処理例外・terminate・abort 発生時に即座に復元.
*	   2. 監視プロセス       : 本体がどのような形で終了しても別プロセスが検知して復元.
*	   3. 次回起動時の復元   : 上記が全て失敗しても次回起動時に復元.
**/
namespace MouseSpeedGuard {
	// 監視プロセスとして起動された場合、本体の終了を監視して復元する.
	//	※WinMain の先頭で呼ぶこと.
	//	※true が返った場合は監視処理を行ったため、本体処理をせずに終了すること.
	bool RunWatchdogIfRequested( const char* lpCmdLine );

	// 復元保証を開始する(起動時に一度だけ呼ぶ).
	//	前回異常終了していた場合は保存していた速度に復元する.
	//	戻り値 : 元のマウス速度.
	__int64 Start();

	// マウス速度を元に戻し、復元保証を終了する(正常終了時に呼ぶ).
	void Stop();
}
